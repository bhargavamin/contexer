def reconcile_session_cmd(rest: list) -> None:
    """`contexer reconcile-session [--session ID] [--dry-run]` — turn recorded evidence into
    decisions pending review, and print the receipt.

    Always exits 0: `reconcile_session` never raises and reports what it could not do as
    `incomplete`, so a reconciliation problem is a line in the report, not a broken shell."""
    session = ""
    args = list(rest)
    if "--session" in args:
        index = args.index("--session")
        session = args[index + 1] if index + 1 < len(args) else ""
        # A flag is never a session id: `--session --dry-run` used to swallow the flag as the
        # VALUE, silently scoping the pass to a session that cannot exist AND dropping the
        # dry run — a write where the developer asked for none.
        if not session or session.startswith("-"):
            print("Missing value for --session.\n"
                  "Usage: contexer reconcile-session [--session ID] [--dry-run]",
                  file=sys.stderr)
            sys.exit(1)
        del args[index:index + 2]
    dry_run = "--dry-run" in args
    if dry_run:
        args.remove("--dry-run")
    if args:
        print(f"Unknown argument: {' '.join(args)}\n"
              "Usage: contexer reconcile-session [--session ID] [--dry-run]", file=sys.stderr)
        sys.exit(1)

    from contexer import reconcile
    repo = _cli_repo()
    if not repo:
        print("No repo detected — run this inside a project directory.", file=sys.stderr)
        return
    _safe_print(reconcile.format_receipt(
        reconcile.reconcile_session(repo, session, dry_run=dry_run)))


def _flag_value(args: list, flag: str, usage: str) -> str:
    """Pull `--flag VALUE` out of `args` in place, exiting with `usage` on a missing or
    flag-shaped value — the reconcile-session rule, since `--reason --replaced-by x` swallowing
    a flag as the VALUE is how a retirement gets recorded with a nonsense reason."""
    if flag not in args:
        return ""
    index = args.index(flag)
    value = args[index + 1] if index + 1 < len(args) else ""
    if not value or value.startswith("-"):
        print(f"Missing value for {flag}.\n{usage}", file=sys.stderr)
        sys.exit(1)
    del args[index:index + 2]
    return value


def _lifecycle_cmd(rest: list, *, retiring: bool) -> None:
    """`contexer retire <id> --reason <text> [--replaced-by <id>]` and
    `contexer restore <id> [--reason <text>]`.

    One id, deliberately: retiring moves a decision out of every active surface at once, and a
    list argument is how one nobody re-read disappears (the same rule `approve_decision` states
    for approval). Exits non-zero when the store refuses, so a script can tell."""
    usage = ("Usage: contexer retire <id> --reason <text> [--replaced-by <id>]" if retiring
             else "Usage: contexer restore <id> [--reason <text>]")
    args = list(rest)
    reason = _flag_value(args, "--reason", usage)
    replacement = _flag_value(args, "--replaced-by", usage) if retiring else ""
    if len(args) != 1 or args[0].startswith("-") or "," in args[0]:
        print(f"{'Retire' if retiring else 'Restore'} takes exactly one decision id.\n{usage}",
              file=sys.stderr)
        sys.exit(1)

    from contexer import lifecycle
    repo = _cli_repo()
    if not repo:
        print("No repo detected — run this inside a project directory.", file=sys.stderr)
        sys.exit(1)
    ok, message = (lifecycle.retire_decision(repo, args[0], reason, replacement) if retiring
                   else lifecycle.restore_decision(repo, args[0], reason))
    if not ok:
        print(message, file=sys.stderr)
        sys.exit(1)
    _safe_print(message)


def _guard_run(rest: list) -> None:
    """`contexer guard [path…] [--explain]` — the commit-time run path.

    Deliberately NOT `_run_guarded`-wrapped: a broken guard must never block a
    commit, so any exception, or the engine's own `error: True`, degrades to a
    single stderr line and exit 0 rather than a traceback or a nonzero exit."""
    try:
        from contexer import guard_engine

        if os.environ.get("CONTEXER_GUARD") == "0":
            sys.exit(0)

        explain = "--explain" in rest
        paths = [a for a in rest if not a.startswith("--")] or None
        repo = _cli_repo()

        if explain:
            _print_guard_explain(guard_engine.guard_candidates(repo, paths, explain=True))
            sys.exit(0)

        result = guard_engine.guard_staged(repo, paths)
        if result.get("error"):
            print("contexer guard: internal error, skipping checks", file=sys.stderr)
            sys.exit(0)
        if result.get("skipped") == "env":
            sys.exit(0)

        advisories = result.get("advisories") or []
        violations = result.get("violations") or []
        # Printed first, since a run that reports nothing else is exactly when the
        # developer most needs to know a file went unscanned. Guarded on its OWN,
        # though: this function's outer handler degrades to exit 0, so without this an
        # exception while rendering an informational notice (a malformed row, an
        # encoding the fallback still cannot write) would swallow the blocking violation
        # printed below it and pass the commit. A purely advisory line must never sit on
        # the critical path of the one output that changes the exit code.
        try:
            if result.get("unchecked"):
                _print_guard_unchecked(result["unchecked"])
        except Exception:
            pass
        if advisories:
            _print_guard_advisories(advisories, result.get("total_advisories"))
        if violations:
            if advisories:
                print()
            _print_guard_violations(violations)
            sys.exit(1)
        sys.exit(0)
    except SystemExit:
        raise
    except Exception:
        print("contexer guard: internal error, skipping checks", file=sys.stderr)
        sys.exit(0)


def _guard_dismiss(rest: list) -> None:
    """`contexer guard --dismiss <hash|n>` — permanently suppress one advisory
    pair. Management path (called under `_run_guarded`). The hash form (usually
    copy-pasted straight off an advisory line) acts directly with no prompt; the
    numeric form re-derives the current candidate listing and requires an
    explicit y/N confirmation, since an index can silently mean something
    different on a later run."""
    from contexer import guard_engine

    i = rest.index("--dismiss")
    if i + 1 >= len(rest):
        print("contexer guard --dismiss: requires a hash or index", file=sys.stderr)
        sys.exit(1)
    arg = rest[i + 1]
    paths = [a for a in rest[:i] + rest[i + 2:] if not a.startswith("--")] or None
    # Resolved ONCE and reused for both the candidates lookup and dismiss_guard below:
    # unlike arm_guard/disarm_guard, dismiss_guard does not call resolve_repo itself
    # (it writes straight to the sidecar keyed on whatever path it's given), so passing
    # it something different from what guard_candidates just searched would dismiss a
    # pair found under one repo against a completely different sidecar file.
    repo = _cli_repo()

    candidates = guard_engine.guard_candidates(repo, paths, explain=True)
    cand = next((c for c in candidates if c.get("hash") == arg), None)

    if cand is None and arg.isdigit():
        candidates = guard_engine.guard_candidates(repo, paths, explain=False)
        idx = int(arg)
        if idx < 1 or idx > len(candidates):
            print(f"contexer guard --dismiss: no candidate at index {idx} "
                  f"({len(candidates)} currently listed)", file=sys.stderr)
            sys.exit(1)
        cand = candidates[idx - 1]
        try:
            reply = input(f'Dismiss "{cand.get("title")}" for {cand.get("file")}? '
                          f'[y/N]: ').strip().lower()
        except (EOFError, KeyboardInterrupt):
            print("\nCancelled.")
            return
        if reply not in ("y", "yes"):
            print("Cancelled.")
            return
    elif cand is None:
        print(f"contexer guard --dismiss: hash {arg!r} not found among "
              f"current candidates", file=sys.stderr)
        sys.exit(1)

    guard_engine.dismiss_guard(repo, cand["decision_id"], cand["file"])
    print(f"Dismissed [{cand['decision_id'][:8]}] for {cand['file']}.")


def _guard_arm(rest: list) -> None:
    """`contexer guard arm <id> --regex '<pattern>' [--flags i] [--paths <glob>]
    [--message <hint>]` or `contexer guard arm <id> --check secret`. Delegates
    entirely to `guard_engine.arm_guard`.

    Its ValueError refusals ("machine-checkable", "only approved decisions can
    be armed") are a documented CONTRACT — a rejected request, not a broken
    file — so they are caught and printed here under this command's own name.
    Left to `_run_guarded`'s generic ValueError arm they came out prefixed
    "Corrupt config:" and followed by advice to fix or remove a config file,
    which is both wrong and destructive to act on."""
    from contexer import guard_engine

    if not rest:
        print("contexer guard arm: requires a decision id", file=sys.stderr)
        sys.exit(1)
    entry_id, opts = rest[0], rest[1:]

    def _opt(name: str) -> str | None:
        if name in opts:
            i = opts.index(name)
            if i + 1 < len(opts):
                return opts[i + 1]
        return None

    check = _opt("--check")
    regex = _opt("--regex")
    if check == "secret":
        check_type, pattern = "secret", ""
    elif regex is not None:
        check_type, pattern = "regex", regex
    else:
        print("contexer guard arm: requires --regex '<pattern>' or --check secret",
              file=sys.stderr)
        sys.exit(1)

    repo = _cli_repo()
    try:
        msg = guard_engine.arm_guard(repo, entry_id, check_type, pattern=pattern,
                                      flags=_opt("--flags") or "", paths=_opt("--paths") or "",
                                      message=_opt("--message") or "")
    except ValueError as e:
        print(f"contexer guard arm: {e}", file=sys.stderr)
        sys.exit(1)
    print(msg)


def _guard_disarm(rest: list) -> None:
    """`contexer guard disarm <id>` — remove a decision's armed rule. Its
    ValueError refusal (unknown id) is a contract refusal, reported under this
    command's own name — see `_guard_arm` for why it must not fall through to
    `_run_guarded`'s "Corrupt config:" arm."""
    from contexer import guard_engine

    if not rest:
        print("contexer guard disarm: requires a decision id", file=sys.stderr)
        sys.exit(1)
    repo = _cli_repo()
    try:
        print(guard_engine.disarm_guard(repo, rest[0]))
    except ValueError as e:
        print(f"contexer guard disarm: {e}", file=sys.stderr)
        sys.exit(1)


def _guard_list() -> None:
    """`contexer guard list` — show every currently armed rule, repo + global."""
    from contexer import store, guard_engine, revisions

    repo = _cli_repo()
    personal = guard_engine._armed_rules(store.load(repo).get("entries") or []) if repo else []
    glob = guard_engine._armed_rules(store.load_global().get("entries") or [])
    rows = [(e, "personal") for e in personal] + [(e, "global") for e in glob]
    if not rows:
        print("No armed guard rules.")
        return
    print(f"{len(rows)} armed guard rule(s):\n")
    for entry, scope in rows:
        gc = entry.get("guard_check") or {}
        id8 = (entry.get("id") or "")[:8]
        title = entry.get("title") or revisions.derive_title(revisions.current_content(entry))
        check_type = gc.get("type", "")
        detail = gc.get("pattern") if check_type == "regex" else "HIGH_CONFIDENCE_PATTERNS"
        paths = gc.get("paths") or "*"
        print(f"  [{id8}] ({scope}, {check_type}) {title}")
        print(f"      pattern={detail!r}  paths={paths}")


def _print_candidate_card(index: int, total: int, item: dict) -> None:
    """Render one anchor-backfill review card: the decision, its candidate
    paths, and the Y/E/S/Q prompt legend."""
    print("─" * 60)
    print(f"Decision {index} of {total}\n")
    print(f"[{item['decision_id'][:8]}] {item['title']}")
    print("Candidate anchors:")
    for path in item["candidates"]:
        print(f"  {path}")
    print()
    print("[Y] anchor all shown  [E] edit list (comma-separated)  [S] skip  [Q] quit")


def _prompt_edited_paths(repo: str) -> list[str] | None:
    """The [E]dit sub-flow: prompt for a comma-separated file list and
    validate each entry the same way the write layer will see it — resolved
    through _guard_relpath (rejecting ../-escaping and absolute spellings,
    exactly what _anchor_sources itself drops) THEN existence-checked, so a
    path this calls valid is guaranteed to actually anchor. Prints the
    dropped (invalid) entries. Returns the valid paths (possibly empty), or
    None on Ctrl-C/EOF."""
    from contexer import guard_engine

    try:
        raw = input("Files (comma-separated): ").strip()
    except (KeyboardInterrupt, EOFError):
        return None
    typed = [path.strip() for path in raw.split(",") if path.strip()]
    valid, invalid = [], []
    for path in typed:
        resolved = guard_engine._guard_relpath(repo, path)
        if guard_engine._escapes_repo(resolved) or not (Path(repo) / resolved).is_file():
            invalid.append(path)
        else:
            valid.append(resolved)
    if invalid:
        print(f"Not found in working tree, dropped: {', '.join(invalid)}")
    return valid


def _guard_anchors(rest: list) -> None:
    """`contexer guard anchors [--list]` — interactive review over trusted,
    unanchored decisions (guard_engine.anchor_candidates_for_backfill).
    Ratified selections apply in ONE batch via store.apply_backfill_anchors,
    on [Q]uit too — but an interrupt (Ctrl-C/EOF) aborts and writes nothing.

    `--list` is the only accepted argument: it prints the candidate table
    read-only, and is also the non-TTY/agent-facing surface, since the
    interactive loop needs a keyboard and refuses otherwise."""
    from contexer import store, guard_engine

    unknown = [a for a in rest if a != "--list"]
    if unknown:
        print(f"contexer guard anchors: unknown argument(s): {' '.join(unknown)} — "
              "the only accepted flag is --list.", file=sys.stderr)
        sys.exit(1)

    repo = _cli_repo()
    candidates = guard_engine.anchor_candidates_for_backfill(repo)

    if "--list" in rest:
        if not candidates:
            print("No trusted, unanchored decisions with derivable anchor candidates.")
            return
        print(f"{len(candidates)} decision(s) with anchor candidates:\n")
        for decision in candidates:
            print(f"  [{decision['decision_id'][:8]}] {decision['title']}")
            for path in decision["candidates"]:
                print(f"      {path}")
        return

    if not candidates:
        print("No trusted, unanchored decisions with derivable anchor candidates.")
        return

    if not sys.stdin.isatty():
        print("contexer guard anchors: requires an interactive terminal — use "
              "`contexer guard anchors --list` to preview candidates without prompting.",
              file=sys.stderr)
        sys.exit(1)

    print(f"\n{len(candidates)} decision(s) with anchor candidates for "
          f"{Path(repo).name}\n")

    selections: dict = {}
    skipped = 0
    aborted = False
    for i, item in enumerate(candidates, 1):
        _print_candidate_card(i, len(candidates), item)

        try:
            choice = input("Choice: ").strip().upper()
        except (KeyboardInterrupt, EOFError):
            aborted = True
            break

        if choice in ("Y", "YES"):
            selections[item["decision_id"]] = item["candidates"]
        elif choice in ("E", "EDIT"):
            valid = _prompt_edited_paths(repo)
            if valid is None:
                aborted = True
                break
            if valid:
                selections[item["decision_id"]] = valid
            else:
                print("No valid files given, skipping.")
                skipped += 1
        elif choice in ("Q", "QUIT"):
            break
        else:
            skipped += 1
            print("Skipped.")

    if aborted:
        # An interrupt writes NOTHING — not even selections ratified before it.
        print("\nAborted — nothing was anchored.")
        return

    applied = store.apply_backfill_anchors(repo, selections) if selections else 0

    print("\n" + "─" * 60)
    parts = []
    if applied:
        parts.append(f"{applied} anchored")
    if skipped:
        parts.append(f"{skipped} skipped")
    print(f"Anchor backfill complete: {', '.join(parts) if parts else 'nothing changed'}.")


_GUARD_FENCE_START = "# >>> contexer guard >>>"
_GUARD_FENCE_END = "# <<< contexer guard <<<"
# Substrings the pre-commit framework (https://pre-commit.com) writes into every
# hook it generates — either one is enough to identify the file as framework-owned.
_GUARD_FRAMEWORK_MARKERS = ("File generated by pre-commit", "pre-commit.com")


def _guard_bin_path() -> str:
    """Absolute path to the contexer binary, resolved once at install time and
    embedded literally in the hook script. The path is embedded (rather than a
    bare `contexer` / `command -v contexer` in the hook body) because
    GUI-launched editors — and their embedded terminals and git clients — don't
    always inherit the shell's PATH, which would silently disable the guard for
    exactly those users.

    The RUNNING entry point (`sys.argv[0]`) is preferred over `shutil.which`:
    `which` finds whatever is first on PATH, which is very often an OLDER global
    install than the one the developer just ran — and baking a pre-guard binary
    into the hook makes `"<bin>" guard` exit 1 on EVERY commit. argv[0] only
    qualifies when it is an absolute, executable, contexer-named file that isn't
    a `.py` source file (a `python -m contexer` / `python server.py` invocation
    puts a module path there, not a console script). Otherwise `shutil.which`,
    and argv[0] as the last resort so a `which` miss never produces a hook with
    no path in it. The result is capability-probed before any hook is written
    (see `_guard_bin_supports_guard`)."""
    argv0 = sys.argv[0] or ""
    name = os.path.basename(argv0)
    if (os.path.isabs(argv0) and name.startswith("contexer")
            and not name.endswith(".py") and os.access(argv0, os.X_OK)
            and os.path.isfile(argv0)):
        return os.path.abspath(argv0)
    found = shutil.which("contexer")
    return os.path.abspath(found or argv0)


def _guard_bin_supports_guard(bin_path: str) -> bool:
    """Whether `bin_path` is a contexer new enough to have the `guard` command.

    Cheap capability probe (`<bin> help`, short timeout) run before writing the
    hook: an older binary has no `guard` subcommand, so the installed hook's
    `"<bin>" guard || exit $?` would fail and BLOCK every commit in the repo.
    Refusing the install is strictly better than installing a hook that bricks
    committing. Any failure (missing file, timeout, non-zero exit) reads as
    unsupported — the probe must never itself be the reason a hook gets
    written."""
    try:
        out = subprocess.run([bin_path, "help"], capture_output=True, text=True,
                              timeout=10)
    except Exception:
        return False
    return out.returncode == 0 and "guard" in (out.stdout or "")


def _guard_require_capable_bin() -> str:
    """`_guard_bin_path` + capability probe, or a loud refusal. Returns the path
    to embed in the hook."""
    bin_path = _guard_bin_path()
    if not _guard_bin_supports_guard(bin_path):
        print(f"contexer guard --install-hook: {bin_path} does not support the "
              "`guard` command (it is missing, or an older contexer). Installing "
              "the hook anyway would make every commit in this repo fail.",
              file=sys.stderr)
        print("Upgrade that install (`pip install -U contexer` / `uv tool upgrade "
              "contexer`), or re-run this command using the contexer you want the "
              "hook to call.", file=sys.stderr)
        sys.exit(1)
    return bin_path


def _guard_hook_block(bin_path: str) -> str:
    """The fenced hook body embedding the absolute binary path, shell-quoted
    (`shlex.quote`) so a path containing `$`, a backtick, a quote or a backslash
    can neither expand nor break the script — either of which would fail the
    hook and block commits. The `-x` existence guard means uninstalling or
    upgrading-away the package can never break a commit either: the hook just
    silently no-ops instead of erroring."""
    q = shlex.quote(bin_path)
    return (
        f'{_GUARD_FENCE_START}\n'
        f'if [ "${{CONTEXER_GUARD:-1}}" != "0" ] && [ -x {q} ]; then\n'
        f'  {q} guard || exit $?\n'
        f'fi\n'
        f'{_GUARD_FENCE_END}\n'
    )


def _guard_precommit_stanza() -> str:
    """The `.pre-commit-config.yaml` stanza to hand the developer when an
    existing hook was generated by the pre-commit framework — mirrors the
    keys in `.pre-commit-hooks.yaml` at the repo root."""
    return (
        "  - repo: local\n"
        "    hooks:\n"
        "      - id: contexer-guard\n"
        "        name: contexer guard\n"
        "        entry: contexer guard\n"
        "        language: system\n"
        "        verbose: true\n"
        "        pass_filenames: false\n"
        "        always_run: true\n"
    )


def _guard_hooks_path_override(repo: str) -> str:
    """`git config core.hooksPath` for `repo`, or "" if unset. Never raises."""
    try:
        out = subprocess.run(["git", "-C", repo, "config", "core.hooksPath"],
                              capture_output=True, text=True, timeout=2)
        if out.returncode == 0:
            return out.stdout.strip()
    except Exception:
        pass
    return ""


def _guard_hooks_dir(repo: str) -> Path:
    """The real hooks directory for `repo`, correct across plain repos, linked
    worktrees, and submodules — `.git` may be a FILE, not a directory, so
    `<root>/.git/hooks` is only right for a plain repo. `git rev-parse
    --git-path hooks` resolves it in every layout. Its output is relative to
    `repo` unless the git dir lives outside the worktree (linked worktrees
    share the main worktree's hooks dir), so only join when it's relative."""
    out = subprocess.run(["git", "-C", repo, "rev-parse", "--git-path", "hooks"],
                          capture_output=True, text=True, timeout=2)
    raw = out.stdout.strip() if out.returncode == 0 else ".git/hooks"
    p = Path(raw)
    return p if p.is_absolute() else Path(repo) / p


def _guard_strip_fence(content: str) -> str:
    """Remove exactly the fenced contexer block (marker line to marker line,
    plus the single trailing newline that belongs to the block) from `content`.
    Everything else — including foreign content before/after — is byte-preserved."""
    start = content.find(_GUARD_FENCE_START)
    if start == -1:
        return content
    end_marker = content.find(_GUARD_FENCE_END, start)
    if end_marker == -1:
        return content  # malformed (no closing marker) — leave untouched
    end = end_marker + len(_GUARD_FENCE_END)
    if end < len(content) and content[end] == "\n":
        end += 1
    return content[:start] + content[end:]


def _guard_read_hook(hook_path: Path) -> tuple[str | None, str]:
    """The hook file's exact text, or (None, reason) when it cannot be read.

    Decoded from BYTES rather than read through text mode, for two reasons:

    1. The codec must be pinned. A perfectly ordinary hook that echoes a
       non-ASCII message (`echo "✖ lint failed"`) decoded fine under a UTF-8
       locale and raised UnicodeDecodeError under LC_ALL=C — crashing
       --install-hook and --uninstall-hook with a traceback and making status
       report "not installed" for a hook that was.
    2. Text mode also translates newlines, which is not byte-preserving. Reading
       a CRLF hook through it yields LF, so appending our block silently stripped
       the \\r from every one of the developer's lines (verified: a
       `#!/bin/sh\\r\\n` hook came back LF-only); on Windows the write side would
       have turned our LF-only block into CRLF, handing `#!/bin/sh` a \\r on every
       line. `Path.read_text(newline=...)` is no help — that parameter is 3.13+
       and this package supports 3.12.

    The reason is carried out instead of being flattened into "not UTF-8": a
    mode-0o000 or EIO hook is an OSError, and sending that developer after an
    encoding problem wastes their time. None always means "do not touch this
    file" — never "empty", never "not ours"."""
    try:
        return hook_path.read_bytes().decode("utf-8"), ""
    except UnicodeDecodeError:
        return None, "is not readable as UTF-8"
    except OSError as exc:
        return None, f"could not be read ({exc.strerror or exc})"


def _guard_hook_status_line() -> str:
    """The `contexer status` guard-hook line for the cwd's repo. Read-only —
    never writes, never refuses; a status command must survive whatever it's
    diagnosing (not in a repo, no hook yet, a foreign or framework hook, or one
    it cannot decode)."""
    from contexer import store

    repo = store.git_root(os.getcwd())
    if not repo:
        return "(not in a git repo)"
    try:
        hook_path = _guard_hooks_dir(repo) / "pre-commit"
        if hook_path.exists():
            content, reason = _guard_read_hook(hook_path)
            if content is None:
                # Distinguished from "not installed": suggesting --install-hook here
                # would send the developer into a command that cannot read the file
                # either, with no hint as to why.
                return f"unknown — {hook_path} {reason}"
            if _GUARD_FENCE_START in content:
                return f"installed at {hook_path}"
    except Exception:
        pass
    return "not installed (contexer guard --install-hook)"


def _guard_install_hook() -> None:
    """`contexer guard --install-hook` — wire the guard into the cwd repo's
    `.git/hooks/pre-commit`. Refusal order is load-bearing:

    1. `core.hooksPath` set → hooks for this repo live entirely outside
       `.git/hooks` (husky, `.githooks`, etc.); writing there would produce a
       dead file nothing ever runs.
    2. An existing pre-commit-framework-generated hook → appending to it would
       be silently wiped by the next `pre-commit install`.
    3. Otherwise: absent → write fresh; present-and-foreign → append; already
       ours → no-op (idempotent).
    4. Immediately before either write, the resolved binary is capability-probed
       (`_guard_require_capable_bin`) and the install refused if it has no
       `guard` command — the "already installed" no-op path never probes, so a
       re-run in an already-wired repo costs no subprocess.

    A management path — called under `_run_guarded` like `arm`/`disarm`, not
    the fail-soft commit-time run path."""
    from contexer import store

    repo = store.git_root(os.getcwd())
    if not repo:
        print("Not inside a git repository.", file=sys.stderr)
        sys.exit(1)

    override = _guard_hooks_path_override(repo)
    if override:
        print(f"contexer guard --install-hook: core.hooksPath is set to {override!r} — "
              "hooks for this repo live outside .git/hooks (husky, .githooks, or "
              "similar), so writing there would create a dead file nothing runs.",
              file=sys.stderr)
        print("Add this to that hook manager's pre-commit script instead:", file=sys.stderr)
        for line in _guard_hook_block(_guard_bin_path()).splitlines():
            print(f"  {line}", file=sys.stderr)
        sys.exit(1)

    hook_path = _guard_hooks_dir(repo) / "pre-commit"
    if hook_path.exists():
        content, reason = _guard_read_hook(hook_path)
        if content is None:
            # A fourth refusal, in the same spirit as the three above: we cannot read
            # the file, so we cannot append to it without risking the developer's own
            # hook. Hand them the block rather than a traceback.
            print(f"contexer guard --install-hook: {hook_path} exists but {reason}, "
                  "so appending to it could corrupt it.", file=sys.stderr)
            print("Add this to that hook by hand instead:", file=sys.stderr)
            for line in _guard_hook_block(_guard_bin_path()).splitlines():
                print(f"  {line}", file=sys.stderr)
            sys.exit(1)
        if any(marker in content for marker in _GUARD_FRAMEWORK_MARKERS):
            print(f"contexer guard --install-hook: {hook_path} was generated by the "
                  "pre-commit framework — appending here would be wiped by the next "
                  "`pre-commit install`.", file=sys.stderr)
            print("Add this to .pre-commit-config.yaml instead:", file=sys.stderr)
            print(_guard_precommit_stanza(), file=sys.stderr)
            sys.exit(1)
        if _GUARD_FENCE_START in content:
            print("contexer guard: hook already installed.")
            return
        sep = "" if content.endswith("\n") else "\n"
        # write_bytes, matching the byte-exact read: the developer's own lines go back
        # exactly as they came in, whatever their line endings, and our block stays
        # LF-only on every platform (a \r in a `#!/bin/sh` script breaks it).
        hook_path.write_bytes(
            (content + sep + _guard_hook_block(_guard_require_capable_bin())).encode("utf-8"))
        print(f"contexer guard: appended to existing hook at {hook_path}")
        return

    bin_path = _guard_require_capable_bin()
    hook_path.parent.mkdir(parents=True, exist_ok=True)
    hook_path.write_bytes(("#!/bin/sh\n" + _guard_hook_block(bin_path)).encode("utf-8"))
    hook_path.chmod(0o755)
    print(f"contexer guard: installed pre-commit hook at {hook_path}")


def _guard_uninstall_hook() -> None:
    """`contexer guard --uninstall-hook` — remove exactly the fenced block from
    the cwd repo's `.git/hooks/pre-commit`; remove the whole file when nothing
    but our block (and the shebang we write with it) remains. Foreign content
    is byte-preserved. No-op with a message when nothing is installed."""
    from contexer import store

    repo = store.git_root(os.getcwd())
    if not repo:
        print("Not inside a git repository.", file=sys.stderr)
        sys.exit(1)

    hook_path = _guard_hooks_dir(repo) / "pre-commit"
    if not hook_path.exists():
        print("contexer guard: no hook installed.")
        return
    content, reason = _guard_read_hook(hook_path)
    if content is None:
        # Never "no hook installed" here — ours may well be in there. Say what is
        # actually wrong and leave the developer a way out, rather than tracebacking
        # out of the one command that removes the block.
        print(f"contexer guard --uninstall-hook: {hook_path} {reason}, so the block "
              f"cannot be removed safely. Delete the lines between "
              f"{_GUARD_FENCE_START!r} and {_GUARD_FENCE_END!r} by hand.",
              file=sys.stderr)
        sys.exit(1)
    if _GUARD_FENCE_START not in content:
        print("contexer guard: no hook installed.")
        return

    remainder = _guard_strip_fence(content)
    if remainder.strip() in ("", "#!/bin/sh"):
        hook_path.unlink()
        print(f"contexer guard: removed {hook_path}")
    else:
        hook_path.write_bytes(remainder.encode("utf-8"))
        print(f"contexer guard: removed contexer block from {hook_path}")


def guard(rest: list | None = None) -> None:
    """`contexer guard` — the commit-time hook entrypoint, plus its management
    subcommands (`arm`, `disarm`, `list`, `--dismiss`, `--install-hook`,
    `--uninstall-hook`). The run path is deliberately NOT `_run_guarded`-wrapped
    (see `_guard_run`); the management subcommands are deliberate developer acts
    and fail loudly like every other mutating command."""
    rest = rest or []
    if rest and rest[0] == "arm":
        _run_guarded(lambda: _guard_arm(rest[1:]))
    elif rest and rest[0] == "disarm":
        _run_guarded(lambda: _guard_disarm(rest[1:]))
    elif rest and rest[0] == "list":
        _run_guarded(_guard_list)
    elif rest and rest[0] == "anchors":
        _run_guarded(lambda: _guard_anchors(rest[1:]))
    elif "--dismiss" in rest:
        _run_guarded(lambda: _guard_dismiss(rest))
    elif "--install-hook" in rest:
        _run_guarded(_guard_install_hook)
    elif "--uninstall-hook" in rest:
        _run_guarded(_guard_uninstall_hook)
    else:
        _guard_run(rest)


def main() -> None:
    args = sys.argv[1:]

    if not args:
        from contexer.server import main as _server
        _server()
        return

    cmd, rest = args[0], args[1:]
    if cmd in ("version", "--version", "-V"):
        version()
    elif cmd in ("help", "--help", "-h"):
        _usage()
    elif cmd == "install":
        _run_guarded(lambda: install(rest))
    elif cmd == "uninstall":
        _run_guarded(lambda: uninstall(rest))
    elif cmd == "reinstall":
        _run_guarded(reinstall)
    elif cmd == "review":
        review()
    elif cmd == "retire":
        _run_guarded(lambda: _lifecycle_cmd(rest, retiring=True))
    elif cmd == "restore":
        _run_guarded(lambda: _lifecycle_cmd(rest, retiring=False))
    elif cmd == "ui":
        _run_guarded(lambda: ui_cmd(rest))
    elif cmd == "status":
        status(rest)
    elif cmd == "pull":
        _run_guarded(lambda: pull(rest))
    elif cmd == "share":
        _run_guarded(lambda: share_cmd(rest))
    elif cmd == "reconcile":
        _run_guarded(lambda: reconcile_cmd(rest))
    elif cmd == "login":
        _run_guarded(lambda: login_cmd(rest))
    elif cmd == "logout":
        _run_guarded(lambda: logout_cmd(rest))
    elif cmd == "guard":
        guard(rest)
    elif cmd == "scope-audit":
        _run_guarded(lambda: scope_audit_cmd(rest))
    elif cmd == "reconcile-session":
        _run_guarded(lambda: reconcile_session_cmd(rest))
    else:
        print(f"Unknown command: {cmd}\n", file=sys.stderr)
        _usage(sys.stderr)
        sys.exit(1)
