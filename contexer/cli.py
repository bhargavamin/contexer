def login_cmd(rest: list | None = None) -> None:
    """`contexer login [--endpoint URL]`: sign in to Contexer Teams via the browser (OAuth).

    Self-configuring — writes config.toml itself, so no manual setup. Endpoint defaults to prod
    (or localhost under CONTEXER_ENV=local); override with --endpoint."""
    from contexer import auth, config

    rest = rest or []
    endpoint = None
    if "--endpoint" in rest:
        i = rest.index("--endpoint")
        if i + 1 >= len(rest):
            print("contexer login: --endpoint requires a URL", file=sys.stderr)
            sys.exit(1)
        endpoint = rest[i + 1]
    try:
        safe_to_sync = auth.login(endpoint=endpoint)
    except (ValueError, RuntimeError, config.ConfigError) as e:
        # ValueError: bad --endpoint; RuntimeError: OAuth flow failure (state mismatch,
        # no code, no token); ConfigError: an unusable ~/.contexer/config.toml reached the
        # profile write — it is NOT a ValueError subclass, so it needs naming here or it
        # surfaces as a traceback out of a login that already spent the browser flow.
        # All three are user-actionable — print cleanly, no traceback.
        print(f"contexer login: {e}", file=sys.stderr)
        sys.exit(1)
    # Skipped only when login could not clear the previous session's queued shares (#232):
    # _post_login_sync DRAINS the outbox, so running it would push those account-less entries
    # up as this account's rows - the exact write the discard exists to prevent. Login itself
    # already warned and named the file; a stale `last sync` line is the cheap side of this.
    if safe_to_sync:
        _post_login_sync()  # refresh team sync so `contexer status` isn't stale after login


def _post_login_sync() -> None:
    """Best-effort team refresh right after a successful login, so `contexer status` doesn't
    keep showing the stale pre-auth `last sync: failed`.

    Refreshes BOTH the current working repo and the repo `contexer status` actually displays
    (the `.current_repo` pointer) — these differ when login is run outside the project you
    last worked in (e.g. logging in from the CLI repo while status still points at your app),
    which is exactly when the stale line is most visible. Uses `team_context.refresh()`: it
    bounds each pull to a short transport timeout (never stalls login on a slow cloud), never
    raises, and drains any queued offline shares. Login has already succeeded and printed, so
    nothing here may fail the command or emit a traceback."""
    try:
        import os

        from contexer import store, team_context

        repos: list[str] = []
        for candidate in (store.git_root(os.getcwd()), store.current_repo_path()):
            if candidate and candidate not in repos:
                repos.append(candidate)
        upserted = removed = 0
        for repo in repos:
            up, rm = team_context.refresh(repo)  # bounded timeout, never raises
            upserted += up
            removed += rm
    except Exception:
        return  # login is done — never let a post-login sync problem surface as a failure
    if upserted or removed:
        msg = f"Synced {upserted} team decision(s)"
        if removed:
            msg += f", removed {removed}"
        print(msg + ".")


def logout_cmd(rest: list | None = None) -> None:
    """`contexer logout`: remove stored Contexer Teams credentials."""
    from contexer import auth

    if auth.logout():
        print("Logged out of Contexer Teams.")
    else:
        print("Not logged in.")


def ui_cmd(rest: list | None = None) -> None:
    """`contexer ui [--open] [--stop] [--status] [--port N] [--foreground] [--reset-token]`.

    Starts (or reports on) the local console — a loopback web UI over every store on this
    machine. The printed URL carries a short-lived pairing code, never the console token."""
    from contexer.ui import daemon

    rest = rest or []
    if "--stop" in rest:
        print("Console stopped." if daemon.stop() else "Console was not running.")
        return
    if "--status" in rest:
        _print_ui_status(daemon.status())
        return

    port = _ui_port(rest)
    if "--foreground" in rest:
        # Imported here, not at module scope: server.py pulls in http.server and the whole
        # store, and cli.py is imported by every `contexer` invocation.
        from contexer.ui import server
        # server.main returns the process exit code: a failed bind must not look like a clean
        # run to whatever supervises `contexer ui --foreground`.
        code = server.main(["--port", str(port)])
        if code:
            sys.exit(code)
        return
    if "--reset-token" in rest:
        old = daemon.read_state()  # stop() drops the statefile, so read the port off it first
        if daemon.stop() and old is not None:
            daemon.await_port_free(old.port)
        daemon.clear_state()  # a fresh token is minted only when no statefile exists

    state = daemon.read_state()
    ours = state is not None and state.port == port and daemon.is_alive(state)
    # await_port_free, not port_occupied alone: SIGTERM is asynchronous, and `--stop` drops the
    # statefile, so the documented `contexer ui --stop && contexer ui` restart arrives while our
    # own dying daemon still holds the socket and nothing is left to recognise it by. Blaming
    # "another process" there sends the user to a different port to escape themselves.
    if not ours and daemon.port_occupied(port) and not daemon.await_port_free(port):
        print(f"Port {port} is in use by another process — the console cannot bind it.",
              file=sys.stderr)
        print(f"Pick another one: set `[ui] port` in {_ui_config_path()}, "
              f"or run `contexer ui --port N`.", file=sys.stderr)
        sys.exit(1)
    # ensure_running short-circuits on a live daemon and hands back ITS port, so without this
    # the URL printed below would name a port nothing was ever bound on. Refuse rather than
    # SIGTERM the incumbent: a mistyped --port must not kill a console someone is using, and
    # `--stop` (or `--reset-token`, which already stops it) is the explicit way to move it.
    if "--port" in rest and state is not None and state.port != port and daemon.is_alive(state):
        print(f"A console is already running on port {state.port} — there is one console per "
              f"machine, so `--port {port}` cannot apply to it.", file=sys.stderr)
        print(f"Move it: contexer ui --stop && contexer ui --port {port}", file=sys.stderr)
        sys.exit(1)

    running = daemon.ensure_running(port)
    if running is None:
        print(f"Could not start the console — see {daemon.LOG_PATH}.", file=sys.stderr)
        sys.exit(1)
    url = daemon.console_url(*running)
    print(f"Console: {url}")
    print(f"  log:          {daemon.LOG_PATH}")
    if "--open" in rest:
        import webbrowser
        webbrowser.open(url)


def _ui_config_path() -> Path:
    """config.toml under THIS invocation's home, not config.CONFIG_PATH (frozen at import) —
    same resolution status() uses, so the file we read is the file we name in errors."""
    return Path.home() / ".contexer" / "config.toml"


def _ui_port(rest: list) -> int:
    """The port `contexer ui` targets: --port wins, else `[ui] port` from config.toml."""
    from contexer import config

    if "--port" in rest:
        i = rest.index("--port")
        value = rest[i + 1] if i + 1 < len(rest) else ""
        if not value.isdigit() or not 1 <= int(value) <= 65535:
            print("contexer ui: --port requires a port number (1-65535)", file=sys.stderr)
            sys.exit(1)
        return int(value)
    try:
        return config.load_ui_settings(_ui_config_path()).port
    except config.ConfigError as e:
        print(f"contexer ui: {e}", file=sys.stderr)
        sys.exit(1)


def _print_ui_status(info: dict) -> None:
    """`contexer ui --status`, laid out like `contexer status`."""
    if info["running"]:
        state = f"running (pid {info['pid']}, started {info['started_at']})"
    elif info["stale"]:
        state = "not running (stale statefile — the next `contexer ui` replaces it)"
    else:
        state = "not running"
    print(f"contexer console {info['version'] or _version()}")
    print(f"  state:        {state}")
    print(f"  port:         {info['port']}")
    if info["url"]:
        print(f"  url:          {info['url']}")
    print(f"  statefile:    {info['state_path']}")
    print(f"  log:          {info['log_path']}")


def _safe_print(text: str = "", **kwargs) -> None:
    """print(), but never raises on a surrogate-bearing string — a staged
    filename that wasn't valid UTF-8, carried through as a surrogate-escaped
    path (see guard_engine._staged_files). Some terminal/locale combinations encode
    stdout in strict mode, where printing a lone surrogate raises
    UnicodeEncodeError; guard rendering must degrade to a lossy-but-visible
    rendering instead, never let a print failure turn a real violation into a
    silently-passed commit (the guard's own outer try/except would otherwise
    swallow the exception and fail OPEN — correct per the guard's fail-open
    invariant, but a worse outcome than just rendering the escape visibly)."""
    try:
        print(text, **kwargs)
    except UnicodeEncodeError:
        # The encoding of the stream actually being written to, not stdout's: callers
        # pass `file=sys.stderr` (the guard's unchecked notice), and the two streams can
        # carry different encodings, in which case re-encoding via stdout's could raise
        # a second time inside the handler for the first.
        stream = kwargs.get("file") or sys.stdout
        enc = getattr(stream, "encoding", None) or "utf-8"
        print(text.encode(enc, "backslashreplace").decode(enc, "replace"), **kwargs)


def _print_guard_advisories(advisories: list, total_advisories: int | None) -> None:
    """Non-blocking advisory block: instruction-first, addressed to whoever reads
    it (human or committing agent). `total_advisories` is only present when
    guard_staged actually capped the list, so the suppressed-count line only
    appears then."""
    n = len(advisories)
    _safe_print(f"⚠️ Contexer: review this commit against {n} approved decision(s) before proceeding:")
    for a in advisories:
        id8 = (a.get("decision_id") or "")[:8]
        _safe_print(f"  - [{id8}] {a.get('title')} — {a.get('file')}  "
                    f"(dismiss: contexer guard --dismiss {a.get('hash')})")
    if total_advisories and total_advisories > n:
        _safe_print(f"  ({total_advisories - n} more suppressed)")


def _print_guard_violations(violations: list) -> None:
    """Blocking violations, plus a footer naming both ways past them: a one-commit
    env bypass, or permanently disarming the rule."""
    for v in violations:
        id8 = (v.get("decision_id") or "")[:8]
        line = f"✗ {v.get('path')}:{v.get('line')} violates decision [{id8}]: {v.get('title')}"
        if v.get("message"):
            line += f" — {v['message']}"
        _safe_print(line)
    _safe_print()
    _safe_print("To bypass this commit: CONTEXER_GUARD=0 git commit …")
    _safe_print("To remove the rule: contexer guard disarm <id>")


_GUARD_UNCHECKED_SHOWN = 5   # names listed before "+N more", mirroring the advisory cap


def _print_guard_unchecked(unchecked: list) -> None:
    """Staged files no armed rule could be run against, on stderr, never affecting the
    exit code. A check that did not happen must not read as a check that found nothing:
    the engine used to skip an over-cap or unreadable file with no trace at all, so a
    commit carrying a secret inside `contexer/store.py` passed as clean. Same
    honest-on-exhaustion rule as `_budgeted`'s "(git is slow ...)" row and
    `anchors._BudgetExceeded`. Capped like the advisory block, since the interesting
    part is that a gap exists, not the full list.

    Two kinds of gap share the list and get their own line, because they are gaps in
    different things and one message cannot be true of both: a row with a `file` is a staged
    file that went unscanned, a row with a `decision_id` is an armed RULE that could not run
    at all (an unparseable pattern, an unknown check type). The second is the one a developer
    cannot otherwise notice — the rule is armed, the commit passes, and nothing ever says the
    check did not happen."""
    files = [u for u in unchecked if u.get("file")]
    dead = [u for u in unchecked if not u.get("file")]
    if files:
        _safe_print(f"contexer guard: {len(files)} staged file(s) not checked by armed "
                    f"rules: {_guard_gap_names(files, lambda u: str(u.get('file')))}",
                    file=sys.stderr)
    if dead:
        _safe_print(f"contexer guard: {len(dead)} armed rule(s) could not run: "
                    f"{_guard_gap_names(dead, lambda u: str(u.get('decision_id'))[:8])}",
                    file=sys.stderr)


def _guard_gap_names(rows: list, name) -> str:
    """`a.py (too-large), b.py (budget), +2 more` — capped at _GUARD_UNCHECKED_SHOWN."""
    shown = rows[:_GUARD_UNCHECKED_SHOWN]
    names = ", ".join(f"{name(u)} ({u.get('reason')})" for u in shown)
    return names + (f", +{len(rows) - len(shown)} more" if len(rows) > len(shown) else "")


def _print_guard_explain(candidates: list) -> None:
    """`--explain`: the full candidate table, including rejected pairs with why."""
    if not candidates:
        _safe_print("No candidate decision/file pairs for the staged changes.")
        return
    _safe_print(f"{len(candidates)} candidate pair(s):\n")
    for c in candidates:
        id8 = (c.get("decision_id") or "")[:8]
        tag = "EMITTED " if c.get("emitted") else "REJECTED"
        _safe_print(f"  [{tag}] [{id8}] {c.get('title')} — {c.get('file')}  "
                    f"({c.get('reason')})  hash={c.get('hash')}")


def _cli_repo() -> str:
    """Same repo-resolution idiom as pull()/share_cmd() (git root, else the
    shared last-resort pointer) — factored out after a dismiss-path divergence
    once sent guard commands to a different store than the rest of the CLI."""
    from contexer import store
    return store.git_root(os.getcwd()) or store.resolve_repo("")


